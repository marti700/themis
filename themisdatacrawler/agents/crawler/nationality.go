// ResolveNationality converts an ISO 3166-1 alpha-2 code to its Spanish
// nationality adjective in feminine form (agreeing with the implied noun
// "nacionalidad" as used on legal forms). Returns the original value unchanged
// if the code is not found, so unknown codes pass through.
func ResolveNationality(isoCode string, _ *string) string {
	if nat, ok := isoToNationality[isoCode]; ok {
		return nat
	}
	return isoCode
}
